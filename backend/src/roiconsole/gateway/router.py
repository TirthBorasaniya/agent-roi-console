"""Routing table and the cheapest-model-meeting-the-bar routing policy."""

# ============= Standard Library =============
from dataclasses import dataclass
from pathlib import Path
from typing import Any

# ============= Third-Party =============
import yaml

# ============= Local =============
from roiconsole.common.config import config_path, load_yaml

# ============= Constants =============
ROUTING_TABLE_FILE = "routing_table.yaml"


# ============= Types =============


class RoutingTableMissingError(FileNotFoundError):
    """Raised when routed requests arrive before experiment E1 generated the table."""


@dataclass(frozen=True)
class Candidate:
    """One model's measured standing for a step class."""

    model: str
    step_success: float
    n_trials: int
    mean_cost_usd: float


@dataclass(frozen=True)
class RoutePlan:
    """
    Ordered models to try for one request.

    Attributes
    ----------
    models : list of str
        Cheapest qualifying model first, then the remaining qualifying models by cost.
    o_below_bar : bool
        True when no candidate met the success bar and the plan falls back to the
        candidates ordered by measured success.
    """

    models: list[str]
    o_below_bar: bool


class RoutingTable:
    """
    configs/routing_table.yaml, generated by E1.

    Parameters
    ----------
    candidates_dict : dict
        step_class to candidates sorted by mean cost.
    metadata_dict : dict
        generated_at, evaluation_date, source results file, and its hash.
    """

    def __init__(
        self, candidates_dict: dict[str, list[Candidate]], metadata_dict: dict[str, Any]
    ) -> None:
        self._candidates_dict = candidates_dict
        self.metadata_dict = metadata_dict

    @classmethod
    def load(cls, path: Path | None = None) -> "RoutingTable":
        """Load the table, raising RoutingTableMissingError before E1 has run."""
        path = path or config_path(ROUTING_TABLE_FILE)
        if not path.is_file():
            raise RoutingTableMissingError(f"{path} not generated yet; run make eval-steps")
        data = load_yaml(path)
        candidates_dict = {
            step_class: sorted(
                (Candidate(**c) for c in entry["candidates"]), key=lambda c: c.mean_cost_usd
            )
            for step_class, entry in data["step_classes"].items()
        }
        metadata_dict = {k: v for k, v in data.items() if k != "step_classes"}
        return cls(candidates_dict, metadata_dict)

    def step_classes(self) -> list[str]:
        """Return the step classes in the table."""
        return sorted(self._candidates_dict)

    def candidates(self, step_class: str) -> list[Candidate]:
        """Return a step class's candidates, cheapest first."""
        if step_class not in self._candidates_dict:
            raise KeyError(f"step class {step_class!r} is not in the routing table")
        return list(self._candidates_dict[step_class])

    def models(self) -> list[str]:
        """Return every model that appears in the table."""
        return sorted({c.model for cand in self._candidates_dict.values() for c in cand})

    def to_dict(self) -> dict[str, Any]:
        """Serialize for writing back to YAML."""
        return {
            **self.metadata_dict,
            "step_classes": {
                step_class: {"candidates": [c.__dict__ for c in candidates]}
                for step_class, candidates in self._candidates_dict.items()
            },
        }

    def write(self, path: Path) -> None:
        """Write the table as YAML."""
        path.write_text(yaml.safe_dump(self.to_dict(), sort_keys=False), encoding="utf-8")


# ============= Policy =============


def plan_route(table: RoutingTable, step_class: str, min_step_success: float) -> RoutePlan:
    """
    Order candidates for a request.

    Policy (SPEC 5.3): the cheapest candidate whose measured step success is at
    least `min_step_success` goes first; the other qualifying candidates follow
    by cost as fallbacks. When none qualifies, the plan orders every candidate
    by success (highest first) and is flagged below the bar, so a run still
    executes and its failure is measured rather than hidden.

    Parameters
    ----------
    table : RoutingTable
        Measured candidates.
    step_class : str
        Request step class.
    min_step_success : float
        Success bar for the step class.

    Returns
    -------
    plan : RoutePlan
        Ordered models.
    """
    candidate_list = table.candidates(step_class)
    qualifying_list = [c for c in candidate_list if c.step_success >= min_step_success]
    if qualifying_list:
        return RoutePlan([c.model for c in qualifying_list], o_below_bar=False)
    ranked_list = sorted(candidate_list, key=lambda c: (-c.step_success, c.mean_cost_usd))
    return RoutePlan([c.model for c in ranked_list], o_below_bar=True)
